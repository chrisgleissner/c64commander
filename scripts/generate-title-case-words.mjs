// Generates src/generated/titleCaseWords.ts — the short-word list the SID title-caser uses to tell
// an ordinary English word set in capitals (THE, LAST, EXIT) from an initialism (NTSC, DXPP, NOP).
//
// Only three- and four-letter words are emitted, and that is the whole trick. Words of two letters
// or fewer are protected outright (IK, DJ, TV), and words of five or more are treated as shouting on
// length alone, so the list is only ever consulted in the narrow band where neither rule decides.
// That turns what would be a ~600 KB dictionary into ~15 KB of source, and it is an exact answer for
// that band rather than a frequency-ranked approximation.
//
// Roman numerals are excluded: III and VII are in the dictionary as words, and admitting them would
// have the title-caser render "Strange Visitor III" as "Strange Visitor Iii".
//
// The source dictionary is a build-host input, not a runtime one — the emitted module is checked in
// so the app works offline and CI never needs the word list installed. Re-run by hand if the rules
// change:
//
//   node scripts/generate-title-case-words.mjs
//   node scripts/generate-title-case-words.mjs --check

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const DICTIONARIES = ["/usr/share/dict/american-english", "/usr/share/dict/words"];
const OUT = resolve(process.cwd(), "src/generated/titleCaseWords.ts");
const check = process.argv.includes("--check");

const readDictionary = () => {
  for (const path of DICTIONARIES) {
    try {
      return readFileSync(path, "utf8");
    } catch {
      /* try the next one */
    }
  }
  console.error(`[title-case-words] no dictionary found. Looked in: ${DICTIONARIES.join(", ")}`);
  process.exit(2);
};

/** Roman numerals for 1..100, which is the range a tune title plausibly counts in. */
const romanNumerals = () => {
  const table = [
    [100, "c"],
    [90, "xc"],
    [50, "l"],
    [40, "xl"],
    [10, "x"],
    [9, "ix"],
    [5, "v"],
    [4, "iv"],
    [1, "i"],
  ];
  const out = new Set();
  for (let value = 1; value <= 100; value += 1) {
    let left = value;
    let text = "";
    for (const [amount, glyph] of table) {
      while (left >= amount) {
        text += glyph;
        left -= amount;
      }
    }
    out.add(text);
  }
  return out;
};

const roman = romanNumerals();
const words = [
  ...new Set(
    readDictionary()
      .split("\n")
      .map((line) => line.trim().toLowerCase())
      .filter((word) => /^[a-z]{3,4}$/.test(word))
      .filter((word) => !roman.has(word)),
  ),
].sort();

const body = `/*
 * C64 Commander - Configure and control your Commodore 64 Ultimate over your local network
 * Copyright (C) 2026 Christian Gleissner
 *
 * Licensed under the GNU General Public License v3.0 or later.
 * See <https://www.gnu.org/licenses/> for details.
 */

// GENERATED by scripts/generate-title-case-words.mjs — do not edit by hand.
//
// Every three- and four-letter English word, minus the roman numerals for 1..100. Used by
// \`sidDisplayName\` to tell a shouted English word from an initialism; see the generator for why
// only this length band is needed.

const WORDS =
  ${JSON.stringify(words.join(" "))}.split(" ");

/** Whether a three- or four-letter lower-case string is an ordinary English word. */
export const SHORT_ENGLISH_WORDS: ReadonlySet<string> = new Set(WORDS);
`;

if (check) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    current = "";
  }
  if (current !== body) {
    console.error("[title-case-words] src/generated/titleCaseWords.ts is stale. Re-run the generator.");
    process.exit(1);
  }
  console.log(`[title-case-words] up to date (${words.length} words)`);
  process.exit(0);
}

writeFileSync(OUT, body, "utf8");
console.log(`[title-case-words] wrote ${words.length} words to ${OUT}`);
