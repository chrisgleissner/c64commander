/**
 * Compile the bundled VICE `.vpl` palettes into a TypeScript module.
 *
 * Done at build time so the app never parses a palette at runtime: the decode hot path wants a
 * 16-entry lookup table that already exists, not a file to read. The generated module is committed,
 * and `--check` fails the lint run if it has drifted from the `.vpl` sources.
 *
 *   node scripts/compile-palettes.mjs           # write src/generated/vicPalettes.ts
 *   node scripts/compile-palettes.mjs --check    # verify it is up to date
 */

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const SOURCE_DIR = resolve(here, "..", "src", "assets", "palettes");
const OUTPUT = resolve(here, "..", "src", "generated", "vicPalettes.ts");

/** The VIC-II has 16 colors; a palette that does not define all of them is not usable. */
const PALETTE_SIZE = 16;
/** Index order is fixed by the hardware, so the names are the machine's, not the file's. */
const INDEX_NAMES = [
  "Black",
  "White",
  "Red",
  "Cyan",
  "Purple",
  "Green",
  "Blue",
  "Yellow",
  "Orange",
  "Brown",
  "Pink",
  "Dark gray",
  "Gray",
  "Light green",
  "Light blue",
  "Light gray",
];

/**
 * Parse a VICE palette file.
 *
 * The format is a comment block carrying `NAME:` and `DESC:` tags, then one `RR GG BB` line per
 * color in hardware index order, with anything after `#` ignored.
 */
export const parseVpl = (text, id) => {
  let name = id;
  let description = "";
  const rgb = [];

  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (line.startsWith("#")) {
      const tag = line.replace(/^#\s*/, "");
      if (tag.startsWith("NAME:")) name = tag.slice(5).trim() || name;
      else if (tag.startsWith("DESC:")) description = tag.slice(5).trim();
      continue;
    }
    const body = line.split("#")[0].trim();
    if (!body) continue;
    const parts = body.split(/\s+/);
    if (parts.length < 3) continue;
    const channels = parts.slice(0, 3).map((part) => Number.parseInt(part, 16));
    if (channels.some((value) => !Number.isInteger(value) || value < 0 || value > 255)) {
      throw new Error(`${id}: cannot read "${body}" as an RR GG BB triple`);
    }
    rgb.push(channels);
  }

  if (rgb.length !== PALETTE_SIZE) {
    throw new Error(`${id}: expected ${PALETTE_SIZE} colors, found ${rgb.length}`);
  }
  return { id, name, description, rgb };
};

const render = (palettes) => {
  const entries = palettes
    .map((palette) => {
      const rows = palette.rgb
        .map((channels, index) => {
          const hex = channels.map((value) => value.toString(16).padStart(2, "0")).join("");
          return `      [${channels.join(", ")}], // ${index.toString().padStart(2)} ${INDEX_NAMES[index]} #${hex}`;
        })
        .join("\n");
      return [
        "  {",
        `    id: ${JSON.stringify(palette.id)},`,
        `    name: ${JSON.stringify(palette.name)},`,
        `    description: ${JSON.stringify(palette.description)},`,
        "    rgb: [",
        rows,
        "    ],",
        "  },",
      ].join("\n");
    })
    .join("\n");

  return `/*
 * C64 Commander - Configure and control your Commodore 64 Ultimate over your local network
 * Copyright (C) 2026 Christian Gleissner
 *
 * Licensed under the GNU General Public License v3.0 or later.
 * See <https://www.gnu.org/licenses/> for details.
 */

/*
 * GENERATED by scripts/compile-palettes.mjs from src/assets/palettes/*.vpl — do not edit by hand.
 *
 * The video stream carries 4-bit palette INDICES, never color values, so these tables decide only
 * how this app paints a frame. They cannot change what the device sent.
 */

export interface VicPalette {
  /** Stable key used by the stored setting; the .vpl filename without its extension. */
  readonly id: string;
  readonly name: string;
  readonly description: string;
  /** Sixteen RGB triples, in VIC-II index order. */
  readonly rgb: readonly (readonly [number, number, number])[];
}

export const VIC_PALETTES: readonly VicPalette[] = [
${entries}
];

/** The C64 Ultimate default — what the machine itself renders, and this app's default. */
export const DEFAULT_VIC_PALETTE_ID = "default";
`;
};

const main = () => {
  const files = readdirSync(SOURCE_DIR)
    .filter((file) => file.endsWith(".vpl"))
    .sort();
  const palettes = files.map((file) => parseVpl(readFileSync(join(SOURCE_DIR, file), "utf8"), file.replace(/\.vpl$/, "")));

  if (!palettes.some((palette) => palette.id === "default")) {
    throw new Error("no default.vpl — the app needs a default palette to fall back to");
  }

  const rendered = render(palettes);
  if (process.argv.includes("--check")) {
    const current = readFileSync(OUTPUT, "utf8");
    if (current !== rendered) {
      console.error("vicPalettes.ts is out of date — run: npm run palettes:build");
      process.exit(1);
    }
    console.log(`palettes check: ${palettes.length} palette(s) up to date`);
    return;
  }

  writeFileSync(OUTPUT, rendered);
  console.log(`wrote ${OUTPUT} (${palettes.length} palettes: ${palettes.map((p) => p.id).join(", ")})`);
};

main();
