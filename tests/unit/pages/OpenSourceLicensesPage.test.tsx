import { fireEvent, render, screen, waitFor, within } from "@testing-library/react";
import { MemoryRouter, Route, Routes } from "react-router-dom";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import OpenSourceLicensesPage from "@/pages/OpenSourceLicensesPage";

const NOTICES = [
  "# Third-Party Notices",
  "",
  "This file is generated by `scripts/generate-third-party-notices.mjs` using local dependency metadata and lockfiles.",
  "",
  "Summary: test notices.",
  "",
  "## Dependency notices",
  "",
  "| Ecosystem | Package | Version | License | Source URL |",
  "| --- | --- | --- | --- | --- |",
  "| NPM | left-pad | 1.3.0 | [MIT](https://spdx.org/licenses/MIT.html) | [https://registry.npmjs.org/left-pad](https://registry.npmjs.org/left-pad) |",
].join("\n");

describe("OpenSourceLicensesPage", () => {
  const originalFetch = globalThis.fetch;

  beforeEach(() => {
    globalThis.fetch = vi.fn(async () => new Response(NOTICES));
  });

  afterEach(() => {
    globalThis.fetch = originalFetch;
    vi.restoreAllMocks();
  });

  const renderLicensesRoute = () => {
    render(
      <MemoryRouter initialEntries={["/settings/open-source-licenses"]}>
        <Routes>
          <Route path="/settings/open-source-licenses" element={<OpenSourceLicensesPage />} />
          <Route path="/settings" element={<div>Settings Page</div>} />
        </Routes>
      </MemoryRouter>,
    );
  };

  it("is a modal sheet, so the keypad focus ring stays inside it", async () => {
    renderLicensesRoute();

    await screen.findByText("Summary: test notices.");

    expect(screen.getByRole("dialog", { name: "Open source licenses" })).toHaveAttribute("data-app-surface", "sheet");
  });

  it("tells the reader what the list is, not how the file behind it was made", async () => {
    renderLicensesRoute();
    await screen.findByText("Summary: test notices.");
    const sheet = screen.getByTestId("open-source-licenses-overlay");

    expect(within(sheet).getByText("The open source software this app uses, and the license of each.")).toBeVisible();
    expect(within(sheet).queryByText(/THIRD_PARTY_NOTICES/)).toBeNull();
    expect(within(sheet).queryByText(/This file is generated/)).toBeNull();
    expect(within(sheet).queryByText("Third-Party Notices")).toBeNull();
  });

  it("gives the license and source links of each package a 44 px target", async () => {
    renderLicensesRoute();
    const card = await screen.findByTestId("open-source-license-card");

    for (const name of ["MIT", "https://registry.npmjs.org/left-pad"]) {
      expect(within(card).getByRole("link", { name })).toHaveClass("min-h-11", "min-w-11");
    }
  });

  it("closes on Escape, which is also how the Android Back key arrives", async () => {
    renderLicensesRoute();
    await screen.findByText("Summary: test notices.");

    fireEvent.keyDown(document.body, { key: "Escape", code: "Escape" });

    await waitFor(() => expect(screen.getByText("Settings Page")).toBeInTheDocument());
  });

  it("stays open on other keys", async () => {
    renderLicensesRoute();
    await screen.findByText("Summary: test notices.");

    fireEvent.keyDown(document.body, { key: "ArrowDown", code: "ArrowDown" });

    expect(screen.queryByText("Settings Page")).not.toBeInTheDocument();
    expect(screen.getByTestId("open-source-licenses-overlay")).toBeInTheDocument();
  });

  it("does not close on touch pointer-up before the synthesized click", async () => {
    renderLicensesRoute();
    await screen.findByText("Summary: test notices.");
    const closeButton = screen.getByTestId("open-source-licenses-close");

    fireEvent.pointerUp(closeButton, { pointerType: "touch" });

    expect(screen.getByTestId("open-source-licenses-overlay")).toBeInTheDocument();
    expect(screen.queryByText("Settings Page")).not.toBeInTheDocument();

    fireEvent.click(closeButton);

    await waitFor(() => expect(screen.getByText("Settings Page")).toBeInTheDocument());
  });
});
